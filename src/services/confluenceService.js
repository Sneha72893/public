/**
 * confluenceService.js
 * Creates automated post-mortem pages in Confluence Cloud
 * after an incident is resolved. Uses @forge/api for Confluence REST API.
 *
 * Page structure (ADF):
 *  1. Incident Summary
 *  2. Timeline (detection → escalation → resolution)
 *  3. Root Cause Analysis  (template, engineer fills in)
 *  4. Resolution Steps     (template, engineer fills in)
 *  5. Action Items         (template)
 *  6. Raw Error Log        (from GitHub)
 */

import api, { route } from '@forge/api';
import { getSettings } from './storageService.js';
import { logger } from '../utils/logger.js';
import { POSTMORTEM_LABEL, SEVERITY } from '../utils/constants.js';

// ─── Public API ───────────────────────────────────────────────────────────────

/**
 * Create a post-mortem page in Confluence.
 *
 * @param {object} incident    - Resolved incident record from storageService
 * @param {string} errorLog    - Raw error log text from GitHub
 * @returns {Promise<string>}  - URL of the created Confluence page
 */
export async function createPostMortem(incident, errorLog = '(No log available)') {
  const settings     = await getSettings();
  const spaceKey     = settings.confluenceSpaceKey || process.env.CONFLUENCE_SPACE_KEY || 'ENG';
  const parentTitle  = settings.postmortemParent   || 'Incident Post-Mortems';

  const parentId = await findOrCreateParent(spaceKey, parentTitle);

  const pageTitle = `[${incident.severity}] Post-Mortem: ${incident.workflowName} — ${new Date(incident.detectedAt).toISOString().split('T')[0]}`;

  const adfBody = buildPostMortemAdf(incident, errorLog);

  const body = {
    type:     'page',
    title:    pageTitle,
    space:    { key: spaceKey },
    ...(parentId ? { ancestors: [{ id: parentId }] } : {}),
    body: {
      storage: {
        value:           JSON.stringify(adfBody),
        representation: 'atlas_doc_format',
      },
    },
    metadata: {
      labels: [{ name: POSTMORTEM_LABEL }],
    },
  };

  try {
    const response = await api
      .asApp()
      .requestConfluence(route`/wiki/rest/api/content`, {
        method:  'POST',
        headers: { 'Content-Type': 'application/json' },
        body:    JSON.stringify(body),
      });

    const data = await response.json();

    if (!response.ok) {
      logger.error('Confluence: failed to create post-mortem page', {
        status: response.status, data,
      });
      throw new Error(`Confluence page creation failed: ${JSON.stringify(data)}`);
    }

    const pageId = data.id;
    const pageUrl = await buildPageUrl(pageId, spaceKey, pageTitle);

    logger.info('Confluence post-mortem created', {
      pageId,
      jiraIssueKey: incident.jiraIssueKey,
      pageUrl,
    });

    return pageUrl;
  } catch (err) {
    logger.error('Confluence: createPostMortem threw', { error: err.message });
    throw err;
  }
}

// ─── Helpers ─────────────────────────────────────────────────────────────────

/**
 * Find or create the parent page for all post-mortems.
 *
 * @param {string} spaceKey
 * @param {string} parentTitle
 * @returns {Promise<string|null>} Parent page ID or null
 */
async function findOrCreateParent(spaceKey, parentTitle) {
  try {
    const searchResp = await api
      .asApp()
      .requestConfluence(
        route`/wiki/rest/api/content?spaceKey=${spaceKey}&title=${encodeURIComponent(parentTitle)}&type=page`,
      );

    const search = await searchResp.json();

    if (search.results && search.results.length > 0) {
      return search.results[0].id;
    }

    // Create the parent page if it doesn't exist
    const createResp = await api
      .asApp()
      .requestConfluence(route`/wiki/rest/api/content`, {
        method:  'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          type:  'page',
          title: parentTitle,
          space: { key: spaceKey },
          body: {
            storage: {
              value:           '<p>Index of all incident post-mortems generated by the Incident Response Automation Forge app.</p>',
              representation: 'storage',
            },
          },
        }),
      });

    const created = await createResp.json();
    return created.id || null;
  } catch {
    return null;
  }
}

async function buildPageUrl(pageId, spaceKey, title) {
  return `/wiki/spaces/${spaceKey}/pages/${pageId}`;
}

// ─── ADF Page Builder ─────────────────────────────────────────────────────────

function buildPostMortemAdf(incident, errorLog) {
  const detectedAt  = new Date(incident.detectedAt).toISOString();
  const resolvedAt  = incident.resolvedAt ? new Date(incident.resolvedAt).toISOString() : 'Unknown';
  const duration    = incident.resolvedAt
    ? formatDuration(incident.resolvedAt - incident.detectedAt)
    : 'Unknown';

  const severityEmoji = {
    [SEVERITY.CRITICAL]: '🔴',
    [SEVERITY.HIGH]:     '🟠',
    [SEVERITY.MEDIUM]:   '🟡',
    [SEVERITY.LOW]:      '🟢',
  }[incident.severity] || '⚪';

  const escalationHistory = (incident.escalationHistory || [])
    .map((e, i) => {
      const levelLabel = e.level === 1 ? 'Senior Engineer' : 'Manager';
      return `  ${i + 1}. Escalated to ${levelLabel} at ${new Date(e.timestamp).toISOString()}`;
    })
    .join('\n') || '  None';

  return {
    version: 1,
    type:    'doc',
    content: [
      // ── Header ──────────────────────────────────────────────────────────────
      adfHeading(1, `${severityEmoji} Incident Post-Mortem: ${incident.jiraIssueKey}`),
      adfInfo(`This page was auto-generated by the Incident Response Automation app when Jira issue ${incident.jiraIssueKey} was resolved. Engineers should fill in the Root Cause Analysis and Resolution Steps sections.`),

      // ── Summary Panel ───────────────────────────────────────────────────────
      adfHeading(2, '1. Incident Summary'),
      adfTable([
        ['Field',          'Value'],
        ['Jira Issue',     `${incident.jiraIssueKey} — ${incident.workflowName}`],
        ['Severity',       `${incident.severity} ${severityEmoji}`],
        ['Environment',    incident.environment],
        ['Repository',     incident.repo],
        ['Branch',         incident.branch],
        ['Triggered By',   incident.actor],
        ['Commit SHA',     incident.headSha || 'N/A'],
        ['GitHub Run URL', incident.workflowRunUrl],
        ['Detected At',    detectedAt],
        ['Resolved At',    resolvedAt],
        ['Total Duration', duration],
      ]),

      // ── Timeline ────────────────────────────────────────────────────────────
      adfHeading(2, '2. Incident Timeline'),
      adfCodeBlock(
        `${detectedAt}  — Workflow failure detected by GitHub webhook\n` +
        `${detectedAt}  — Jira issue ${incident.jiraIssueKey} auto-created\n` +
        `${detectedAt}  — Slack/Teams notification sent\n` +
        escalationHistory + '\n' +
        `${resolvedAt}   — Incident resolved (Jira status updated)\n` +
        `${new Date().toISOString()}  — Post-mortem page auto-generated`,
        'text',
      ),

      // ── Root Cause ──────────────────────────────────────────────────────────
      adfHeading(2, '3. Root Cause Analysis'),
      adfWarning('👷 This section requires manual input from the responding engineer.'),
      adfHeading(3, 'What happened?'),
      adfParagraph('(Describe what failed and why — e.g. a dependency broke, config was missing, a code bug was introduced.)'),
      adfHeading(3, 'Why did it happen?'),
      adfParagraph('(Describe the underlying cause — e.g. insufficient testing, missing alerts, process gap.)'),
      adfHeading(3, 'Why wasn\'t it caught earlier?'),
      adfParagraph('(What controls/tests should have caught this sooner?)'),

      // ── Resolution Steps ────────────────────────────────────────────────────
      adfHeading(2, '4. Resolution Steps'),
      adfWarning('👷 This section requires manual input from the responding engineer.'),
      adfParagraph('Describe the exact steps taken to resolve this incident:'),
      adfOrderedList([
        '(Step 1)',
        '(Step 2)',
        '(Step 3 — add more as needed)',
      ]),

      // ── Action Items ────────────────────────────────────────────────────────
      adfHeading(2, '5. Action Items (Prevention)'),
      adfTable([
        ['Action',                    'Owner',    'Due Date', 'Status'],
        ['Add test coverage for X',   '(Assign)', '(Date)',   'Open'],
        ['Improve alerting for Y',    '(Assign)', '(Date)',   'Open'],
        ['Document runbook for Z',    '(Assign)', '(Date)',   'Open'],
      ]),

      // ── Raw Error Log ────────────────────────────────────────────────────────
      adfHeading(2, '6. Raw Error Log (GitHub Actions)'),
      adfCodeBlock(errorLog, 'text'),
    ],
  };
}

// ─── ADF Node Helpers ─────────────────────────────────────────────────────────

function adfHeading(level, text) {
  return { type: 'heading', attrs: { level }, content: [{ type: 'text', text }] };
}

function adfParagraph(text) {
  return { type: 'paragraph', content: [{ type: 'text', text }] };
}

function adfCodeBlock(text, language = 'text') {
  return { type: 'codeBlock', attrs: { language }, content: [{ type: 'text', text }] };
}

function adfInfo(text) {
  return {
    type:    'panel',
    attrs:   { panelType: 'info' },
    content: [adfParagraph(text)],
  };
}

function adfWarning(text) {
  return {
    type:    'panel',
    attrs:   { panelType: 'warning' },
    content: [adfParagraph(text)],
  };
}

function adfTable(rows) {
  return {
    type:    'table',
    attrs:   { isNumberColumnEnabled: false, layout: 'default' },
    content: rows.map((row, i) => ({
      type:    'tableRow',
      content: row.map((cell) => ({
        type:    i === 0 ? 'tableHeader' : 'tableCell',
        attrs:   {},
        content: [adfParagraph(cell)],
      })),
    })),
  };
}

function adfOrderedList(items) {
  return {
    type:    'orderedList',
    content: items.map((text) => ({
      type:    'listItem',
      content: [adfParagraph(text)],
    })),
  };
}

function formatDuration(ms) {
  const totalSeconds = Math.floor(ms / 1000);
  const h = Math.floor(totalSeconds / 3600);
  const m = Math.floor((totalSeconds % 3600) / 60);
  const s = totalSeconds % 60;
  if (h > 0) return `${h}h ${m}m`;
  if (m > 0) return `${m}m ${s}s`;
  return `${s}s`;
}
